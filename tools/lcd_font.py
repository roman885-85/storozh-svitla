lines = [l for l in A.strip().split('\n')]
for i in range(0, len(lines), 2):
    name, art = lines[i].strip(), lines[i + 1].strip()
    ch = {'space': ' ', 'backslash': '\\'}.get(name, name)
    g(ch, '\n'.join(art.split('|')))
# однакові з латиницею
for cy, la in zip('АВЕІКМНОРСТХаеіорсухʼ', 'ABEIKMHOPCTXaeiopcyx’'):
    G[cy] = G[la]
G['ʼ'] = G['’']
def cols(rows):
    return [sum(1 << r for r in range(7) if rows[r][c] == '#') for c in range(5)]
cps = sorted(ord(c) for c in G)
root = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(root, '..', 'firmware', 'avr-mist', 'lcd_font.h')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* Створює tools/lcd_font.py — вручну не правити. Шрифт 5×7 з українськими літерами для дисплея Nokia 5110 (1.0.22).\n'
            '   LCD_CP — коди знаків за зростанням (пошук половинним діленням), LCD_GL — 5 стовпців на знак, біт 0 — верхній рядок. */\n')
    f.write('#pragma once\n#include <stdint.h>\n')
    f.write('static const int LCD_NG = %d;\n' % len(cps))
    f.write('static const uint16_t LCD_CP[] = {' + ','.join(str(c) for c in cps) + '};\n')
    f.write('static const uint8_t LCD_GL[][5] = {\n')
    for c in cps:
        f.write('  {' + ','.join('0x%02x' % v for v in cols(G[chr(c)])) + '},  // ' + (chr(c) if chr(c) not in '\\' else 'backslash') + '\n')
    f.write('};\n')
print('знаків:', len(cps), '→', os.path.normpath(out))
# прев'ю: усі знаки сіткою, ×4
if len(sys.argv) > 1:
    per = 24
    rowsN = (len(cps) + per - 1) // per
    W, H, S = per * 6 + 2, rowsN * 9 + 2, 4
    px = [[0] * W for _ in range(H)]
    for k, c in enumerate(cps):
        x0, y0 = 1 + (k % per) * 6, 1 + (k // per) * 9
        for x, v in enumerate(cols(G[chr(c)])):
            for y in range(7):
                if v >> y & 1: px[y0 + y][x0 + x] = 1
    raw = b''.join(b'\x00' + bytes(v for x in range(W * S) for v in ((40, 52, 40) if px[y // S][x // S] else (178, 196, 160))) for y in range(H * S))
    def chunk(t, d): return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    open(sys.argv[1], 'wb').write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', W * S, H * S, 8, 2, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
    print('прев\'ю:', sys.argv[1])
