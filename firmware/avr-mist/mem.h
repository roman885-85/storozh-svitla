#pragma once
#include <Arduino.h>

/*  Пам'ять (1.0.38). Власник 22.11.2026: «выполнить капитальную оптимизацию для оперативной памяти».

    ESP.getFreeHeap() ядра Arduino рахує разом зі звичайною пам'яттю (DRAM) ще ~32 КБ пам'яті команд (IRAM), куди можна
    писати лише цілими 32-бітними словами: звичайна програма, Wi-Fi й шифрування її не займуть. Тому до 1.0.37 сторінка
    показувала «вільно 55–60 КБ», а справді вільних було 24–28 КБ, і під час запиту до YASNO лишалось ~2 КБ; сторож
    «мало пам'яті» (< 20 КБ) не міг спрацювати ніколи, а «найбільший шматок» завжди був 31 732 Б — це й була порожня IRAM.
    Тут — справжні цифри: лише пам'ять, якою можна користуватись.  */
uint32_t memFree();        // вільно звичайної пам'яті, Б
uint32_t memBlock();       // найбільший цілий шматок
uint32_t memMinIdf();      // найменше від запуску за лічильниками ядра (сума мінімумів окремих куп — занижує)
uint32_t memMin();         // найменше від запуску за нашими замірами (кожні 20 мс)
uint32_t memMinRecent();   // найменше за останні 5–10 хв
uint32_t memIram();        // вільно в пам'яті команд
void     memSample();      // з loop()
void     memStage(const char* name);   // на запуску: скільки вільно після цього кроку
String   memBootLine();    // «Пам'ять на запуску: …» — один рядок у журнал
String   memJson();        // подробиці (стеки задач, кроки запуску) — для вкладки «Журнал»
