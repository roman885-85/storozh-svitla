#pragma once
#include <Arduino.h>

/*  Прошивка мосту батареї через Сторожа (1.0.48). Власник 23.11.2026: «мост бмс можно обновить с дома через страницу
    для бмс». Міст оновлюється сам за адресою файлу (http/https), але з дому файл до об'єкта не дістати, а викладати
    його в інтернет не треба: власник завантажує …-app.bin мосту на сторінку Сторожа, Сторож кладе його у вільний
    розділ прошивки (той, куди лягло б його власне оновлення) і 10 хв роздає мосту по своїй мережі:
    http://10.77.0.1:8081/<разовий ключ>/avr-bms.bin з x-MD5 — міст звіряє файл перед записом.  */
bool   fwrBegin(String& err);                               // початок прийому файлу
bool   fwrWrite(const uint8_t* d, size_t n, String& err);   // шматок файлу (перший — перевірка: застосунок ESP32-C3)
bool   fwrEnd(String& err);                                 // кінець: дописати, порахувати MD5, почати роздавати
void   fwrAbort();
void   fwrStop();                                           // перестати роздавати (власне оновлення Сторожа займе розділ)
bool   fwrBusy();                                           // приймає чи роздає — власне оновлення Сторожа зачекає
String fwrJson();                                           // стан для сторінки
String fwrUrl();                                            // адреса для мосту ("" — не роздає)
void   fwrLoop();                                           // з loop(): рядки журналу
