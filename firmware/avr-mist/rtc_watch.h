#pragma once
#include <Arduino.h>
/*  Стан міста й генератора і відколи — у RTC-пам'яті (1.0.26, власник: «да делай» — щоб після перезапуску Сторож пам'ятав,
    з якого моменту немає світла). Переживає перезапуск і оновлення прошивки, не зникнення живлення. Моменти — секунди
    від 1970 р. (лічильник мікросекунд після запуску починається з нуля). Сама змінна — у zrtc.cpp: див. там, чому так.  */
struct RtcWatchData {
  int8_t gst, lst;           // стан міста й генератора: -1 невідомо, 0 немає, 1 є
  uint8_t gex, lex;          // момент переходу бачили наживо
  int64_t gsince, lsince;    // з якого моменту поточний стан
  int64_t savedAt;           // коли востаннє записано (перевірка: перезапуск був недавно)
};
struct RtcWatch { uint32_t magic, sum; RtcWatchData d; };
extern RtcWatch RW;
